"""Copy the game into docs/ for GitHub Pages.

    py pipeline/build.py
    py pipeline/make_site.py
    git add -A && git commit -m "Publish puzzles" && git push

Only Ready days are published (drafts stay local). GitHub Pages serves
docs/ at https://<user>.github.io/froggle/.
"""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA, SITE = ROOT / "data", ROOT / "docs"


def read_js_obj(path: Path):
    text = path.read_text(encoding="utf8")
    return json.loads(text[text.index("=", text.index("window.")) + 1: text.rstrip().rindex(";")])


def main():
    index = read_js_obj(DATA / "index.js")
    ready = index["dates"]

    if SITE.exists():
        shutil.rmtree(SITE)
    (SITE / "data" / "days").mkdir(parents=True)
    shutil.copyfile(ROOT / "froggle.html", SITE / "index.html")
    shutil.copyfile(DATA / "vocab.js", SITE / "data" / "vocab.js")
    for d in ready:
        shutil.copyfile(DATA / "days" / f"{d}.js", SITE / "data" / "days" / f"{d}.js")
    header = "// Generated by pipeline/make_site.py\n"
    (SITE / "data" / "index.js").write_text(
        header + "window.FROGGLE_INDEX = " + json.dumps({"launch": index["launch"], "dates": ready, "drafts": []}) + ";\n",
        encoding="utf8")
    (SITE / ".nojekyll").write_text("")  # serve files as-is
    print(f"docs/ ready: {len(ready)} day(s) ({ready[0] if ready else '-'} … {ready[-1] if ready else '-'})")


if __name__ == "__main__":
    main()
